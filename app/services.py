async def decide(pid: str, qid: str, deviation_id: str, decision: str) -> AsyncIterator[dict[str, Any]]:
    quote = await store.get_quote(pid, qid)
    if quote is None:
        raise ServiceError("Quote not found.", 404)
    if quote.status != "active":
        raise ServiceError(f"This quote is {quote.status}; open the latest one.", 409)
    dev = next((d for d in quote.deviations if d.id == deviation_id), None)
    if dev is None:
        raise ServiceError("That proposed change no longer exists.", 404)
    brief = await _require_brief(pid)
    req = await store.get(pid, "requests", quote.request_id)
    seller = catalog.SELLERS[quote.seller_id]

    if decision == "keep_original":
        dev.decision = "kept_original"
        quote.readiness = missionlock.readiness(brief, quote)
        await store.save_quote(pid, quote)
        await store.log(pid, "customer", f"Kept '{dev.requirement_label}' - asked {seller['name']} for an alternative", kind="decision")
        yield {"type": "progress", "message": f"You kept '{dev.requirement_label}'. Your brief is unchanged (v{brief.version})."}
        yield {"type": "progress", "message": f"Asking {seller['name']} for an alternative within your brief (AI-simulated)"}
        decision_text = (
            f"The customer KEPT their original requirement '{dev.requirement_label}' and rejected '{dev.proposed}'. "
            f"Question: {dev.card.get('question_for_seller') if dev.card else 'Can you meet the original requirement?'}"
        )
        new_quote = await maker_round(pid, req, seller, brief, round_no=quote.round + 1, previous=quote,
                                      customer_decision=decision_text)
        if new_quote:
            ok = not any(d.severity == "blocked" for d in new_quote.deviations)
            yield {"type": "progress", "message": f"Revised quote received - {'every must-have preserved' if ok else 'still conflicts with a must-have'}"}
        yield {"type": "result", "state": await store.full_state(pid)}
        return

    if decision != "accept":
        raise ServiceError("Unknown decision.")

    if dev.kind == "must" and dev.requirement_id not in ("budget-limit",):
        # Accepting a must-have change is an explicit brief change -> new version.
        target = brief.req(dev.requirement_id)
        offered = quote.offered_specs

        def mutate(b: Brief) -> None:
            r = b.req(dev.requirement_id)
            if r is None:
                return
            if r.attribute and r.op in ("<=", ">=") and getattr(offered, r.attribute, None) is not None:
                r.value_num = float(getattr(offered, r.attribute))
                if re.search(r"\d+(?:\.\d+)?", r.label):
                    r.label = re.sub(r"\d+(?:\.\d+)?", f"{r.value_num:g}", r.label, count=1)
                else:
                    r.label = f"{r.label} ({r.value_num:g} {r.unit or ''})".strip()
            else:
                r.kind = "flexible"
            r.note = f"Changed after accepting {seller['name']}'s proposal ({dev.proposed})."
            r.source = "seller"

        new_brief = await store.new_brief_version(
            pid, mutate, summary=f"You accepted {seller['name']}'s change: {dev.requirement_label} -> {dev.proposed}"
        )
        await store.log(pid, "customer", f"Accepted a must-have change - brief v{new_brief.version} created", kind="change",
                        detail=f"Before: {target.label if target else dev.original}. After: {dev.proposed}.")
        quote.status = "superseded"
        await store.save_quote(pid, quote)
        relinked = quote.model_copy(deep=True)
        relinked.id = store.new_id("qte")
        relinked.brief_version = new_brief.version
        relinked.status = "active"
        relinked.note = f"{seller['name']} proposed this exact change, so its terms were re-linked to brief v{new_brief.version}."
        relinked.created_at = now_iso()
        relinked.deviations = missionlock.quote_deviations(new_brief, relinked)
        for d in relinked.deviations:
            old = next((o for o in quote.deviations if o.id == d.id), None)
            if old and old.card:
                d.card = old.card
        relinked.readiness = missionlock.readiness(new_brief, relinked)
        await store.save_quote(pid, relinked)
        yield {"type": "progress", "message": f"Brief v{new_brief.version} created; the quote is now linked to it."}
    else:
        dev.decision = "accepted"
        quote.readiness = missionlock.readiness(brief, quote)
        await store.save_quote(pid, quote)
        await store.log(pid, "customer", f"Accepted a flexible change: {dev.requirement_label} -> {dev.proposed}", kind="decision")
        yield {"type": "progress", "message": f"Accepted: {dev.proposed}. Your must-haves are unchanged."}
    yield {"type": "result", "state": await store.full_state(pid)}


