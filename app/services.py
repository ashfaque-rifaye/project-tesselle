MILESTONES = [
    ("acknowledged", "Order acknowledged", "seller"),
    ("sample_preparation", "Sample preparation", "seller"),
    ("sample_review", "Sample review", "customer"),
    ("production", "Production", "seller"),
    ("ready_to_ship", "Ready to ship", "seller"),
    ("shipped", "Shipped", "courier"),
    ("delivered", "Delivered", "courier"),
    ("acceptance_review", "Acceptance review", "customer"),
]


async def approve(pid: str, qid: str, idempotency_key: str, acknowledgements: list[str]) -> dict[str, Any]:
    brief = await _require_brief(pid)
    quote = await store.get_quote(pid, qid)
    if quote is None:
        raise ServiceError("Quote not found.", 404)
    existing = await store.get(pid, "orders", "order")
    if existing and existing.get("idempotency_key") == idempotency_key:
        return existing  # duplicate click / second device: same order, no second commitment
    blockers = missionlock.approval_blockers(brief, quote, existing_order=existing is not None)
    unresolved = missionlock.unresolved_charges(quote)
    if unresolved and "unresolved_charges" not in acknowledgements:
        blockers.append("Acknowledge the charges that are not yet known: " + ", ".join(unresolved))
    if blockers:
        await store.log(pid, "agent:missionlock_guard", "Approval blocked", kind="guard", detail=" ".join(blockers))
        raise ServiceError("Approval blocked by MissionLock safeguards.", 409, blockers)

    now = datetime.now(timezone.utc)
    lead_max = quote.lead_time_days_max or 14
    milestones = []
    for i, (key, label, actor) in enumerate(MILESTONES):
        eta = now + timedelta(days=round(lead_max * i / (len(MILESTONES) - 1)))
        milestones.append({"key": key, "label": label, "actor": actor, "estimate": eta.date().isoformat(),
                           "state": "done" if i == 0 else ("current" if i == 1 else "upcoming"), "evidence": None})
    order = {
        "id": "order",
        "order_ref": "SBX-" + store.new_id("o")[2:].upper(),
        "sandbox": True,
        "quote_id": quote.id,
        "seller_name": quote.seller_name,
        "brief_version": brief.version,
        "title": quote.title,
        "specs": quote.offered_specs.model_dump(),
        "price_lines": [p.model_dump() for p in quote.price_lines],
        "known_total_inr": missionlock.known_total(quote),
        "unresolved": unresolved,
        "acceptance_checks": brief.acceptance_checks,
        "idempotency_key": idempotency_key,
        "status": "in_progress",
        "milestones": milestones,
        "delivery_check": None,
        "created_at": now_iso(),
    }
    try:
        await store.db().collection("projects").document(pid).collection("orders").document("order").create(order)
    except gexc.AlreadyExists:
        raise ServiceError("An order already exists for this project - a second commitment is blocked.", 409)
    quote.status = "approved"
    await store.save_quote(pid, quote)
    await store.update_project(pid, approved_brief_version=brief.version)
    await _advance(pid, "fulfil")
    await store.log(pid, "customer", f"Approved brief v{brief.version} + {quote.seller_name}'s quote - sandbox order {order['order_ref']}",
                    kind="decision", detail="Sandbox: no money moved and no real seller was committed.")
    return order


async def advance_order(pid: str, sample_decision: Optional[str] = None) -> dict[str, Any]:
    order = await store.get(pid, "orders", "order")
    if not order:
        raise ServiceError("No order yet.", 404)
    ms = order["milestones"]
    idx = next((i for i, m in enumerate(ms) if m["state"] == "current"), None)
    if idx is None:
        return order
    cur = ms[idx]
    stats = []
    if cur["key"] == "sample_preparation":
        quote = await store.get_quote(pid, order["quote_id"])
        try:
            img, mime, st = await gemini.generate_image(
                "Realistic workshop photo of a finished handmade sample: "
                + (quote.layout_description if quote and quote.layout_description else order["title"])
                + ". On a workbench next to a steel ruler showing the depth, natural light, no text, no logos, no people.",
                purpose="sample-evidence",
            )
            cur["evidence"] = await store.upload_media(f"projects/{pid}/sample", img, mime)
            stats.append(st.as_dict())
        except Exception as e:
            log.warning("sample render failed: %s", e)
    if cur["key"] == "sample_review":
        if sample_decision not in ("approve", "revise"):
            raise ServiceError("Review the sample: approve it or ask for a revision.", 409)
        if sample_decision == "revise":
            ms[idx - 1]["state"] = "current"
            cur["state"] = "upcoming"
            order["milestones"] = ms
            await store.put(pid, "orders", "order", order)
            await store.log(pid, "customer", "Asked for a sample revision - production stays paused", kind="decision")
            return order
        await store.log(pid, "customer", "Approved the sample", kind="decision")
    cur["state"] = "done"
    if idx + 1 < len(ms):
        ms[idx + 1]["state"] = "current"
    order["milestones"] = ms
    await store.put(pid, "orders", "order", order)
    if ms[min(idx + 1, len(ms) - 1)]["key"] == "acceptance_review":
        await _advance(pid, "accept")
    await store.log(pid, "system", f"Simulated milestone: {cur['label']} done", kind="milestone",
                    detail="Demo control - milestones are simulated, not real logistics.", stats=stats or None)
    return order


async def delivery_check(pid: str, photo: Optional[tuple[bytes, str]], use_sample: bool = False) -> dict[str, Any]:
    order = await store.get(pid, "orders", "order")
    if not order:
        raise ServiceError("No order yet.", 404)
    if photo is None and use_sample:
        sample = next((m.get("evidence") for m in order["milestones"] if m.get("evidence")), None)
        if not sample:
            raise ServiceError("No simulated delivery photo is available - upload one.", 409)
        photo = await store.download_media(sample)
    if photo is None:
        raise ServiceError("Add a photo of the delivered item.")
    path = await store.upload_media(f"projects/{pid}/delivery", photo[0], photo[1])
    brief = await store.get_brief(pid, order["brief_version"])
    out, stats = await run_specialist(
        sp.delivery_inspector,
        [
            "Acceptance checks approved before ordering:\n- " + "\n- ".join(order["acceptance_checks"]),
            "Approved specification: " + json.dumps(order["specs"]),
            "Approved brief must-haves: " + "; ".join(r.label for r in brief.musts()) if brief else "",
            types.Part.from_bytes(data=photo[0], mime_type=photo[1]),
            "Photo of the delivered item, taken by the customer.",
        ],
    )
    report = sp.InspectionReport.model_validate(out).model_dump()
    order["delivery_check"] = {"photo_path": path, "report": report, "at": now_iso(), "outcome": None}
    await store.put(pid, "orders", "order", order)
    await _advance(pid, "accept")
    await store.log(pid, "agent:delivery_inspector", report["summary"], kind="agent",
                    detail="Checked against the acceptance checks you approved. A photo cannot prove every characteristic.",
                    stats=[stats])
    return order


async def close_delivery(pid: str, outcome: str, note: str = "") -> dict[str, Any]:
    order = await store.get(pid, "orders", "order")
    if not order or not order.get("delivery_check"):
        raise ServiceError("Run the delivery check first.", 409)
    order["delivery_check"]["outcome"] = outcome
    order["delivery_check"]["note"] = note
    order["status"] = "accepted" if outcome == "accept" else "issue_open"
    if outcome == "accept":
        for m in order["milestones"]:
            m["state"] = "done"
    await store.put(pid, "orders", "order", order)
    await store.log(pid, "customer", "Accepted the item against the approved brief" if outcome == "accept"
                    else f"Reported an issue: {note or 'see evidence'} - evidence preserved for review", kind="decision")
    return order


# =============================================================================================
# Next decision + recap (cross-device continuity)
# =============================================================================================


def next_decision(state: dict[str, Any]) -> dict[str, Any]:
    """Deterministic 'what do I do next' used by the hub, the intent card and the phone surface."""
    p = state["project"]
    briefs = state["briefs"]
    brief = briefs[-1] if briefs else None
    quotes = [q for q in state.get("quotes") or [] if q["status"] in ("active", "approved")]
    order = state.get("order")
    if not brief:
        return {"stage": "inspire", "title": "Share your inspiration", "detail": "Describe it, show a photo or record a voice note."}
    if not brief["confirmed"]:
        n = sum(1 for u in brief["unknowns"] if u["status"] == "open")
        return {"stage": "clarify", "title": "Confirm your brief",
                "detail": f"Check what must stay the same{f' and answer {n} question(s)' if n else ''}."}
    if order:
        if order.get("status") == "accepted":
            return {"stage": "accept", "title": "Completed", "detail": "Accepted against the approved brief. Reorder or modify any time."}
        if order.get("delivery_check") and not order["delivery_check"].get("outcome"):
            return {"stage": "accept", "title": "Accept or report an issue", "detail": "Review the delivery check against your approved brief."}
        cur = next((m for m in order["milestones"] if m["state"] == "current"), None)
        if cur and cur["key"] == "sample_review":
            return {"stage": "fulfil", "title": "Review the sample", "detail": "The maker shared sample evidence. Approve it or ask for a revision."}
        if cur and cur["key"] == "acceptance_review":
            return {"stage": "accept", "title": "Check your delivery", "detail": "Compare the item with the checks you approved."}
        return {"stage": "fulfil", "title": f"Next milestone: {cur['label'] if cur else 'none'}", "detail": "Nothing needs you right now."}
    active = [q for q in quotes if q["status"] == "active"]
    for q in sorted(active, key=lambda q: q["created_at"], reverse=True):
        pend = [d for d in q["deviations"] if d["decision"] == "pending"]
        if pend:
            d = pend[0]
            return {"stage": "compare", "title": (d.get("card") or {}).get("title") or f"Decide on {d['requirement_label']}",
                    "detail": f"{d['original']} -> {d['proposed']}", "quote_id": q["id"], "deviation_id": d["id"],
                    "severity": d["severity"]}
        if q["readiness"] == "ready":
            return {"stage": "approve", "title": "Review and approve the quote",
                    "detail": f"{q['seller_name']}: ready for review against brief v{q['brief_version']}.", "quote_id": q["id"]}
    reqs = state.get("requests") or []
    if any(r["status"] == "draft" for r in reqs):
        return {"stage": "request", "title": "Review what sellers will receive", "detail": "Nothing is sent until you approve it."}
    if any(r["status"] == "sent" for r in reqs):
        return {"stage": "request", "title": "Waiting for sellers", "detail": "No seller has responded yet."}
    if state.get("routes") and state["routes"].get("brief_version") == brief["version"]:
        return {"stage": "routes", "title": "Choose a route", "detail": state["routes"]["narrative"]["headline"]}
    if not state.get("concepts"):
        return {"stage": "visualise", "title": "Visualise a concept", "detail": "Optional: explore a labelled concept before checking routes."}
    return {"stage": "routes", "title": "Explore fulfilment routes", "detail": f"Check buy, source and make against brief v{brief['version']}."}


async def recap(pid: str, speak: bool = False) -> dict[str, Any]:
    state = await store.full_state(pid)
    if not state:
        raise ServiceError("Project not found.", 404)
    nd = next_decision(state)
    brief = state["briefs"][-1] if state["briefs"] else None
    summary = {
        "project": state["project"]["title"],
        "stage": state["project"]["stage"],
        "brief": None if not brief else {
            "version": brief["version"],
            "confirmed": brief["confirmed"],
            "must_haves": [r["label"] for r in brief["requirements"] if r["kind"] == "must"],
            "last_change": brief["change_summary"],
        },
        "quotes": [{"seller": q["seller_name"], "round": q["round"], "readiness": q["readiness"], "status": q["status"],
                    "brief_version": q["brief_version"]} for q in state["quotes"]],
        "order": None if not state["order"] else {"ref": state["order"]["order_ref"], "sandbox": True,
                                                  "status": state["order"]["status"]},
        "next_decision": nd,
        "recent_activity": [e["summary"] for e in state["events"][:6]],
    }
    out, stats = await run_specialist(sp.recap_agent, ["Project state:\n" + json.dumps(summary, ensure_ascii=False)])
    rec = sp.Recap.model_validate(out).model_dump()
    rec["next_decision"] = nd
    rec["stats"] = [stats]
    if speak:
        rec["audio"], tts = await gemini.speak(rec["spoken"])
        rec["stats"].append(tts.as_dict())
    return rec
