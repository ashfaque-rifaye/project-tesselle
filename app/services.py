async def draft_request(
    pid: str,
    *,
    seller_ids: list[str],
    include_concept: bool = True,
    include_photo: bool = False,
    share_budget: bool = True,
) -> dict[str, Any]:
    brief = await _require_brief(pid)
    if not brief.confirmed:
        raise ServiceError("Confirm your brief before sending it to sellers.", 409)
    project = await store.get_project(pid) or {}
    sellers = [catalog.SELLERS[s] for s in seller_ids if s in catalog.SELLERS and catalog.SELLERS[s]["role"] == "maker"]
    if not sellers:
        raise ServiceError("Choose at least one participating maker.")
    shared = {
        "brief_version": brief.version,
        "title": brief.title,
        "purpose": brief.purpose,
        "requirements": [
            {"id": r.id, "label": r.label, "kind": r.kind, "status": r.status} for r in brief.requirements
        ],
        "budget": brief.budget.model_dump(include={"target_inr", "limit_inr"}) if share_budget else None,
        "delivery_region": (brief.delivery.region or "").split(",")[0] or None,
        "concept_image_path": project.get("selected_concept_id") and f"projects/{pid}/concepts/{project['selected_concept_id']}" if include_concept else None,
        "photo_included": bool(include_photo and (project.get("inspiration") or {}).get("image_path")),
        "not_shared": ["Your name and contact details", "Your full address"]
        + ([] if include_photo else ["Photos of your space"])
        + ([] if share_budget else ["Your budget"]),
    }
    out, stats = await run_specialist(
        sp.seller_brief_writer, ["Shared fields (only these may be used):\n" + json.dumps(shared, ensure_ascii=False)]
    )
    sb = sp.SellerBrief.model_validate(out)
    rid = store.new_id("req")
    req = {
        "id": rid,
        "seller_ids": [s["id"] for s in sellers],
        "seller_names": [s["name"] for s in sellers],
        "brief_version": brief.version,
        "shared": shared,
        "summary": sb.summary,
        "questions": sb.questions_for_maker,
        "status": "draft",
        "responses": [],
        "created_at": now_iso(),
    }
    await store.put(pid, "requests", rid, req)
    await _advance(pid, "request")
    await store.log(pid, "agent:seller_brief_writer", "Prepared a privacy-filtered request for your review",
                    kind="agent", detail="Nothing has been sent yet.", stats=[stats])
    return req


async def send_request(pid: str, rid: str) -> AsyncIterator[dict[str, Any]]:
    req = await store.get(pid, "requests", rid)
    if not req:
        raise ServiceError("Request not found.", 404)
    if req["status"] != "draft":
        raise ServiceError("This request was already sent.", 409)
    brief = await _require_brief(pid)
    if brief.version != req["brief_version"]:
        raise ServiceError("Your brief changed after this request was prepared. Review the request again.", 409)
    req["status"] = "sent"
    req["sent_at"] = now_iso()
    await store.put(pid, "requests", rid, req)
    await store.log(pid, "customer", f"Sent the approved request (brief v{brief.version}) to {', '.join(req['seller_names'])}", kind="decision")
    yield {"type": "progress", "message": f"Request sent to {', '.join(req['seller_names'])} - brief v{brief.version} only"}
    for seller_id in req["seller_ids"]:
        seller = catalog.SELLERS[seller_id]
        yield {"type": "progress", "message": f"{seller['name']} is reviewing your brief (AI-simulated demo seller)"}
        quote = await maker_round(pid, req, seller, brief, round_no=1)
        if quote is None:
            yield {"type": "progress", "message": f"{seller['name']} declined - reason recorded"}
        else:
            msg = f"Quote received from {seller['name']} - "
            msg += (f"{len(quote.deviations)} change(s) need your decision" if quote.deviations else "no deviations")
            yield {"type": "progress", "message": msg}
    yield {"type": "result", "state": await store.full_state(pid)}


async def maker_round(
    pid: str,
    req: dict[str, Any],
    seller: dict[str, Any],
    brief: Brief,
    *,
    round_no: int,
    previous: Optional[Quote] = None,
    customer_decision: Optional[str] = None,
) -> Optional[Quote]:
    parts = [
        f"Customer-approved brief v{brief.version}:\n" + brief.model_dump_json(
            include={"version", "title", "purpose", "requirements", "budget", "delivery"}
        ),
        "Brief summary sent to you:\n" + req["summary"],
        "Questions from the customer:\n- " + "\n- ".join(req.get("questions") or []),
        f"This is ROUND {round_no}.",
    ]
    if previous is not None:
        parts.append("Your previous proposal:\n" + previous.model_dump_json(include={"title", "offered_specs", "price_lines", "message"}))
    if customer_decision:
        parts.append("Customer decision on your previous proposal: " + customer_decision)
    out, stats = await run_specialist(sp.maker_agent(seller["name"], seller.get("capabilities", "")), parts)
    mr = sp.MakerResponse.model_validate(out)
    if mr.decision == "decline":
        req["responses"] = (req.get("responses") or []) + [
            {"seller_id": seller["id"], "seller_name": seller["name"], "decision": "decline", "message": mr.message, "at": now_iso()}
        ]
        await store.put(pid, "requests", req["id"], req)
        await store.log(pid, f"seller:{seller['id']}", f"{seller['name']} declined: {mr.message}", kind="seller", stats=[stats])
        return None

    valid_until = (datetime.now(timezone.utc) + timedelta(days=max(1, mr.validity_days))).isoformat(timespec="seconds")
    quote = Quote(
        id=store.new_id("qte"),
        request_id=req["id"],
        seller_id=seller["id"],
        seller_name=seller["name"],
        brief_version=brief.version,
        round=round_no,
        title=mr.title,
        message=mr.message,
        offered_specs=mr.offered_specs,
        responses=mr.responses,
        price_lines=mr.price_lines,
        lead_time_days_min=mr.lead_time_days_min,
        lead_time_days_max=mr.lead_time_days_max,
        valid_until=valid_until,
        sample_plan=mr.sample_plan,
        terms=mr.terms,
        layout_description=mr.layout_description,
        staged=True,
    )
    quote.deviations = missionlock.quote_deviations(brief, quote)
    quote.readiness = missionlock.readiness(brief, quote)

    async def card_for(dev):
        raw, st = await run_specialist(
            sp.deviation_explainer,
            [
                "Brief requirement: " + (brief.req(dev.requirement_id).model_dump_json() if brief.req(dev.requirement_id) else dev.requirement_label),
                "Guard classification: " + dev.model_dump_json(include={"severity", "kind", "original", "proposed", "reason"}),
                f"Seller: {seller['name']} (fictional demo maker). Next brief version would be v{brief.version + 1}.",
            ],
        )
        return raw, st

    async def proposal_render():
        try:
            img, mime, st = await gemini.generate_image(
                "Supplier proposal render of a handmade product described by the maker: "
                + mr.layout_description
                + f". Exact dimensions: {mr.offered_specs.width_cm} cm wide, {mr.offered_specs.depth_cm} cm deep, "
                f"{mr.offered_specs.height_cm} cm high; material {mr.offered_specs.material}. Warm off-white seamless "
                "background, soft workshop light, three-quarter view, no text, no logos, no people.",
                purpose="supplier-proposal",
            )
            path = await store.upload_media(f"projects/{pid}/quotes/{quote.id}", img, mime)
            return path, st.as_dict()
        except Exception as e:  # a missing render never blocks a quote
            log.warning("proposal render failed: %s", e)
            return None, None

    results = await asyncio.gather(*(card_for(d) for d in quote.deviations), proposal_render())
    all_stats = [stats]
    for dev, (raw, st) in zip(quote.deviations, results[:-1]):
        dev.card = raw
        all_stats.append(st)
    quote.image_path, render_stats = results[-1]
    if render_stats:
        all_stats.append(render_stats)

    if previous is not None:
        previous.status = "superseded"
        await store.save_quote(pid, previous)
    await store.save_quote(pid, quote)
    req["status"] = "responded"
    req["responses"] = (req.get("responses") or []) + [
        {"seller_id": seller["id"], "seller_name": seller["name"], "decision": "quote", "quote_id": quote.id, "at": now_iso()}
    ]
    await store.put(pid, "requests", req["id"], req)
    await _advance(pid, "compare")
    blocked = [d for d in quote.deviations if d.severity == "blocked"]
    await store.log(
        pid,
        f"seller:{seller['id']}",
        f"{seller['name']} quoted (round {round_no}, for brief v{brief.version}): {mr.title}",
        kind="seller",
        detail=mr.message,
        stats=[all_stats[0]],
    )
    if quote.deviations:
        await store.log(
            pid,
            "agent:missionlock_guard",
            ("Blocked: " if blocked else "Needs your decision: ")
            + "; ".join(f"{d.requirement_label} -> {d.proposed}" for d in quote.deviations),
            kind="guard",
            detail="Deterministic MissionLock check against the confirmed brief. A seller proposal cannot change a must-have.",
            stats=all_stats[1:],
        )
    else:
        await store.log(pid, "agent:missionlock_guard", "Quote matches every must-have in your brief", kind="guard")
    return quote


