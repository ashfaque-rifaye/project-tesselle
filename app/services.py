async def explore_routes(pid: str) -> AsyncIterator[dict[str, Any]]:
    brief = await _require_brief(pid)
    if not brief.confirmed:
        raise ServiceError("Confirm your brief before exploring routes, so results match what you need.", 409)
    sessions = InMemorySessionService()
    runner = Runner(app_name="route-explorer", node=route_workflow, session_service=sessions)
    session = await sessions.create_session(app_name="route-explorer", user_id="system", state={"project_id": pid})
    msg = types.Content(role="user", parts=[types.Part(text=f"Explore fulfilment routes for brief v{brief.version}")])
    result: Optional[dict[str, Any]] = None
    started = datetime.now(timezone.utc)
    yield {"type": "progress", "node": "start", "message": f"Exploring buy, source, customise and make for brief v{brief.version}"}
    async for ev in runner.run_async(user_id="system", session_id=session.id, new_message=msg):
        node = getattr(ev, "node_name", None) or ""
        out = getattr(ev, "output", None)
        if out is None or node not in PROGRESS:
            continue
        yield {"type": "progress", "node": node, "message": PROGRESS[node](out)}
        if node == "analyst":
            result = out
    if result is None:
        raise ServiceError("Route exploration did not complete.", 500)

    entries = result["entries"]
    groups = {k: [e["item_id"] for e in entries if e["verdict"] == k]
              for k in ("meets", "possible_with_change", "not_suitable", "needs_quote")}
    routes_doc = {
        "brief_version": brief.version,
        "checked_at": now_iso(),
        "entries": entries,
        "groups": groups,
        "sources": result["sources"],
        "narrative": result["narrative"],
        "duration_ms": int((datetime.now(timezone.utc) - started).total_seconds() * 1000),
    }
    await store.put(pid, "routes", "latest", routes_doc)
    await _advance(pid, "routes")
    await store.log(
        pid,
        "agent:route_explorer",
        f"{len(groups['meets'])} meet your brief, {len(groups['possible_with_change'])} possible with a change, "
        f"{len(groups['not_suitable'])} not suitable, {len(groups['needs_quote'])} makers can quote",
        kind="agent",
        detail="ADK Workflow: three scouts in parallel (Firestore vector search with Gemini embeddings), "
        "MissionLock guard verdicts, route analyst explanation. " + result["narrative"]["headline"],
        stats=[result["stats"]],
    )
    yield {"type": "result", "routes": routes_doc}


