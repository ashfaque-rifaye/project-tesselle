// Cross-origin smoke test of the Firebase Hosting front end calling the Cloud Run API.
import { chromium } from "playwright";
const base = process.argv[2] || "https://project-tesselle.web.app";
const out = process.argv[3] || "shots";
const browser = await chromium.launch({ args: ["--use-gl=angle", "--ignore-gpu-blocklist"] });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
const errors = [];
page.on("pageerror", (e) => errors.push("pageerror " + e.message));
page.on("console", (m) => m.type() === "error" && errors.push("console " + m.text()));
await page.goto(base, { waitUntil: "networkidle" });
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/fb-home.png` });
await page.mouse.wheel(0, 2600);
await page.waitForTimeout(2000);
await page.screenshot({ path: `${out}/fb-home-lock.png` });
await page.mouse.wheel(0, -4000);
await page.getByRole("button", { name: /Launch the guided demo/ }).first().click();
await page.waitForURL(/\/p\/prj_/, { timeout: 30000 });
await page.waitForTimeout(2500);
console.log("workspace url:", page.url());
await page.getByRole("button", { name: /Use the demo inspiration/ }).click();
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/fb-inspire.png` });
await page.getByRole("button", { name: /Use this inspiration/ }).click();
await page.waitForURL(/clarify/, { timeout: 120000 });
await page.waitForTimeout(2000);
await page.screenshot({ path: `${out}/fb-clarify.png` });
console.log("clarify reached:", page.url());
console.log("errors:", errors.length ? errors : "none");
await browser.close();
